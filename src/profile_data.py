"""Regenerate docs/data_profile.md: every profiling number with the SQL that produced it.

    uv run python -m src.profile_data
"""

import duckdb

from src.config import DB_PATH, ROOT

CHECKS = [
    ("Orders by status", """
        SELECT order_status, count(*) AS orders FROM stg_orders GROUP BY 1 ORDER BY 2 DESC"""),
    ("Multi-row orders in the child tables (the source of join fan-out)", """
        SELECT
            (SELECT count(*) FROM int_order_items    WHERE n_items > 1)    AS orders_multi_item,
            (SELECT count(*) FROM int_order_items    WHERE n_sellers > 1)  AS orders_multi_seller,
            (SELECT count(*) FROM int_order_payments WHERE n_payments > 1) AS orders_multi_payment,
            (SELECT count(*) FROM int_order_reviews  WHERE n_reviews > 1)  AS orders_multi_review"""),
    ("What a naive items x payments join does to the payment total", """
        SELECT
            (SELECT sum(p.payment_value) FROM stg_order_payments p JOIN stg_order_items i USING (order_id)) AS naive_join_total,
            (SELECT sum(payment_value) FROM stg_order_payments
              WHERE order_id IN (SELECT order_id FROM stg_order_items))                                  AS correct_total"""),
    ("Data-quality flags on fct_orders", """
        SELECT
            count(*) FILTER (WHERE dq_delivered_without_date)   AS delivered_without_date,
            count(*) FILTER (WHERE dq_carrier_before_purchase)  AS carrier_before_purchase,
            count(*) FILTER (WHERE dq_delivered_before_carrier) AS delivered_before_carrier,
            count(*) FILTER (WHERE dq_no_items)                 AS no_items,
            count(*) FILTER (WHERE dq_no_payment)               AS no_payment,
            count(*) FILTER (WHERE dq_payment_mismatch)         AS payment_mismatch_over_1_brl,
            count(*) FILTER (WHERE is_overdue_undelivered)      AS overdue_undelivered
        FROM fct_orders"""),
    ("Month completeness (analysis window = is_complete)", """
        SELECT purchase_month, n_orders, n_delivered,
               round(100 * share_open, 1) AS pct_open,
               round(100 * share_estimate_after_cutoff, 1) AS pct_estimate_after_cutoff,
               is_complete
        FROM dim_month ORDER BY 1"""),
    ("Late-delivery rate by month (complete months only)", """
        SELECT f.purchase_month,
               count(*) FILTER (WHERE is_delivered)                 AS delivered,
               round(100 * avg(CAST(is_late AS DOUBLE)), 1)         AS late_rate_pct,
               round(avg(delivery_days), 1)                         AS avg_delivery_days,
               count(*) FILTER (WHERE is_overdue_undelivered)       AS overdue_undelivered
        FROM fct_orders f JOIN dim_month m USING (purchase_month)
        WHERE m.is_complete
        GROUP BY 1 ORDER BY 1"""),
]


def fmt(v) -> str:
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, int):
        return f"{v:,}"
    if hasattr(v, "date") and callable(v.date):  # pandas Timestamp -> plain date
        return v.date().isoformat()
    return str(v)


def to_markdown(df) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(fmt(v) for v in row) + " |")
    return "\n".join(lines)


def main() -> None:
    out = ["# Data profile", "",
           "Generated by `uv run python -m src.profile_data`. Every number below is the",
           "output of the SQL shown above it, run against `data/processed/olist.duckdb`.", ""]
    with duckdb.connect(str(DB_PATH), read_only=True) as con:
        for title, sql in CHECKS:
            sql = "\n".join(line[8:] if line.startswith(" " * 8) else line for line in sql.strip("\n").splitlines())
            out += [f"## {title}", "", "```sql", sql, "```", "", to_markdown(con.execute(sql).df()), ""]
    path = ROOT / "docs" / "data_profile.md"
    path.write_text("\n".join(out))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
